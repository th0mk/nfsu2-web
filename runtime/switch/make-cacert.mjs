// make-cacert.mjs -- runtime/switch/cacert_pem.c: the CA roots the console trusts for wss://, from Mozilla's bundle
//   node runtime/switch/make-cacert.mjs <cacert.pem from https://curl.se/ca/cacert.pem (check its .sha256)>
import fs from 'node:fs';
const src = process.argv[2];
if (!src) { console.error('usage: node make-cacert.mjs <cacert.pem>'); process.exit(2); }
const pem = fs.readFileSync(src, 'utf8');
const blocks = [...pem.matchAll(/-----BEGIN CERTIFICATE-----[\s\S]*?-----END CERTIFICATE-----/g)].map(m => m[0].replace(/\r/g, ''));
const lines = ['/* generated by runtime/switch/make-cacert.mjs from Mozilla\'s CA bundle (curl.se/ca/cacert.pem, ' + blocks.length + ' roots): do not edit */',
  'const char nfsu2_cacert_pem[] ='];
const BS = String.fromCharCode(92);
for (const b of blocks) for (const l of b.split(String.fromCharCode(10))) lines.push('"' + l + BS + 'n"');
lines.push(';');
fs.writeFileSync(new URL('./cacert_pem.c', import.meta.url), lines.join('\n') + '\n');
console.log(blocks.length + ' roots, ' + blocks.join('\n').length + ' bytes');
