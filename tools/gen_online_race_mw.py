#!/usr/bin/env python3
"""gen_online_race_mw.py -- Most Wanted's input scripts for Online races between
game instances on this server's Online stand-in (web/tools/online-pair.mjs
--game mw; Underground 2's are online-pair's own onlineScript()).

  tools/gen_online_race_mw.py host|join [options] > script.txt

Every step that depends on the game, or on the other instance, waits for its
screen (NFSU2_FNG_LOG's names, runtime/mw/fe_mw.c).  A wait that runs out
goes on to the next line (runtime/autotest.c); online-pair fails the run on it.

Both: a first start: the alias (tools/gen_lan_race_mw.py alias()), the main
menu's Online (its 6th item, 0x4B4E388F, after LAN Play: the main menu's
options in the order 0x544E50 adds them, Career, Challenge Series, Quick
Race, My Cars, LAN Play, Online).  With roam_name set (online-pair
sets it to the instance's name) the game logs in under that name without the
EA Login screens (runtime/mw/online_mw.c): UI_OLISPConnect.fng, then the
Online main menu, OL_MAIN.fng.
From there the race is the LAN one's (tools/gen_lan_race_mw.py): Quick Race
(OL_Quickrace_Main.fng), its race kind (--kind N: N taps DOWN), Enter; Online
only, Dialog.fng then asks "Entering a game room may cause you to lose ..."
(OK highlighted), and OK searches (OL_Find_Session.fng).  host: a search that finds no game ends on "No suitable
matches" (OL_Dialog_Stacked_Buttons.fng): Accept creates the game
(OL_GameRoom.fng).  join: searches again until a search joins the host's game
(OL_GameRoom.fng).  In the room nobody presses anything: the game starts the
race by itself once the room's minimum of players is in it.  Then both wait
for the race (GameFlow [0x925E90] == 6), hand the car to the game's AI driver
at the GO and wait for the results screen.

Options:
  --name NAME          the alias (the Online name is roam_name, from the tool)
  --kind N             the Quick Race kind: N taps DOWN (host and joiners)
  --searches N         join: searches for the host's game before giving up
                       (default 30)
  --race-ms MS         time of the race before the results wait (default
                       120000)
  --results SCREEN     the results screen (waitfng name, default
                       PostRace_Results.fng)
  --results-tmo N      frames to wait for it (default 30000)
  --until STEP         stop after STEP (main, lobby, room, race; default: the
                       results)
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_lan_race_mw import FLOW, alias  # noqa: E402


def quick_race(w, kind):
    """OL_MAIN.fng, on Quick Race: its race kind; Enter brings Dialog.fng, "Entering a game room may cause you to
    lose ..." (Online only; its first button highlighted), whose OK searches (OL_Find_Session.fng)"""
    w('+30   tap RETURN')
    w('+0    waitfng OL_Quickrace_Main.fng@4b4e388a 900')
    for _ in range(kind):
        w('+30   tap DOWN')
    w('+30   tap RETURN')
    w("+0    waitfng Dialog.fng'Entering_a_game_room@b8a7c6cc 900   # Entering a game room may cause you to lose ...")
    w('+30   tap RETURN                                         # OK: search (OL_Find_Session.fng)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('role', choices=['host', 'join'])
    ap.add_argument('--name', default=None)
    ap.add_argument('--kind', type=int, default=0)
    ap.add_argument('--searches', type=int, default=30)
    ap.add_argument('--race-ms', type=int, default=120000)
    ap.add_argument('--results', default='PostRace_Results.fng')
    ap.add_argument('--results-tmo', type=int, default=30000)
    ap.add_argument('--until', choices=['main', 'lobby', 'room', 'race', 'results'], default='results')
    a = ap.parse_args()
    host = a.role == 'host'
    name = a.name or ('OLHOST' if host else 'OLJOIN')
    L = []
    w = L.append

    def stop():
        # (after the results: the game reports the race, rank, later than its results screen comes: a first finisher
        # that closed 1200 frames after its results, before the other finished, sent no report, and a result needs
        # two (runs of 2026-10-30; that the report waits for the race's end is inferred))
        w('+%d close' % (3600 if a.until == 'results' else 300))
        sys.stdout.write('\n'.join(L) + '\n')
        sys.exit(0)

    w('# Most Wanted Online race, %s side, generated by tools/gen_online_race_mw.py %s' % (a.role, ' '.join(sys.argv[1:])))
    alias(w, name)
    if a.until == 'main':
        stop()
    w('+0    tapuntil RIGHT MainMenu.fng@4b4e388f 40 600        # Online')
    w('+0    log online: menu')
    w('+0    tap RETURN')
    w('+0    waitfng OL_MAIN.fng@4b4e388a 3600                  # logged in: the Online main menu, on Quick Race')
    w('+0    log online: lobby')
    if a.until == 'lobby':
        stop()
    if host:
        quick_race(w, a.kind)
        w("+0    waitfng OL_Dialog_Stacked_Buttons.fng'No_suitable@b8a7c6cc 3600   # No suitable matches (Accept)")
        w('+30   tap RETURN                                         # Accept: create the game')
    else:
        w("+0    loop %d                                            # until a search finds the host's game" % a.searches)
        w('+0    log online: search')
        quick_race(w, a.kind)
        w("+0    waitfng OL_GameRoom.fng|OL_Dialog_Stacked_Buttons.fng'No_suitable 3600")
        w('+0    breakfng OL_GameRoom.fng                           # joined')
        w('+0    log online: no game yet')
        w('+0    tap ESCAPE                                         # back to the Online main menu')
        w('+0    waitfng OL_MAIN.fng@4b4e388a 900')
        w('+300  endloop                                            # a pause between two searches')
    w('+0    waitfng OL_GameRoom.fng 3600')
    w('+0    log online: room')
    if a.until == 'room':
        stop()
    w('+0    waitmem %s 6 36000                         # racing' % FLOW)
    w('+0    log online: racing')
    w('+0    autopilot go                                       # the AI takes the car at the GO')
    w('+0    log race-start')
    if a.until == 'race':
        stop()
    w('+%dms log online: race time' % a.race_ms)
    w('+0    waitfng %s %d' % (a.results, a.results_tmo))
    w('+0    log results')
    stop()


if __name__ == '__main__':
    main()
