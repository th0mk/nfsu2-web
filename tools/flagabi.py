#!/usr/bin/env python3
"""Inter-procedural flag liveness (ABI): are the flags really live at call and
return points?

Code generated by MSVC does not read a flag returned by a call, and the callee
does not read the caller's flags on entry.  The lifter, though, treats all flags
as live at calls and at ret (conservative): the six flags of the last
flag-setting instruction before a call are always computed and stored.  This
tool PROVES the assumption:

  live_in[f]  : flags read at f's entry (before they are defined)
  flags_out   : targets of direct calls after which a flag is read
  indirect_rd : indirect call sites after which a flag is read
(the JSON keys have the same names)

Fixed point: call T -> defines F_ALL, uses live_in[T] (indirect: F_ALL);
ret -> live 0, or F_ALL if f is in flags_out.

    ./.venv/bin/python tools/flagabi.py <SPEED2.EXE> [output.json]

output.json is passed to genall.py as FLAGABI=<json> (see lift.flag_liveness).
"""
import sys, os, json, collections, time, multiprocessing as mp
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lift import Lifter, abi_cfg, abi_liveness, F_ALL
from capstone.x86 import X86_OP_IMM

EXE = sys.argv[1]
_L = None

def _init():
    global _L
    _L = Lifter(EXE, comments=False)

def summarize(a):
    try:
        blocks, calls = _L.discover(a)
    except Exception:
        return a, None
    return a, abi_cfg(blocks, _L.in_text, _L.jtab)


def analyse(G):
    """fixed point -> (live_in, flags_out, indirect_rd)"""
    live_in = {a: 0 for a in G}
    flags_out = set()
    for round_no in range(16):
        changed = False
        new_out = set(); indirect_rd = []
        for a, g in G.items():
            ent, _, call_after = abi_liveness(g, a, live_in, a in flags_out)
            if ent != live_in[a]:
                live_in[a] = ent; changed = True
            for site, (cur, kind, target) in call_after.items():
                if cur:
                    if kind == 1: new_out.add(target)
                    else: indirect_rd.append((a, site, cur))
        if new_out - flags_out:
            flags_out |= new_out; changed = True
        print(f'  round {round_no}: live at entry {sum(1 for v in live_in.values() if v)}, '
              f'returning flags {len(flags_out)}, reading after an indirect call {len(indirect_rd)}')
        if not changed: break
    return live_in, flags_out, indirect_rd


if __name__ == '__main__':
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.environ.get('OUT_DIR', 'out'), 'flagabi.json')
    t0 = time.time()
    sys.argv = sys.argv[:2]            # genall expects argv[2]=NSHARD
    import genall                      # discover_all: genall.EXE = sys.argv[1]
    funcs = genall.discover_all()[0]   # every entry, jump-table targets included: a superset of what is lifted
    print(f'{len(funcs)} functions ({time.time()-t0:.0f}s)')
    with mp.Pool(mp.cpu_count(), initializer=_init) as pool:
        G = dict(pool.map(summarize, funcs, chunksize=64))
    G = {a: g for a, g in G.items() if g}
    print(f'summary: {len(G)} functions ({time.time()-t0:.0f}s)')
    live_in, flags_out, indirect_rd = analyse(G)
    json.dump({'live_in': {hex(a): v for a, v in live_in.items() if v}, 'flags_out': sorted(hex(a) for a in flags_out),
               'indirect_rd': [[hex(a), hex(site), cur] for a, site, cur in indirect_rd]}, open(out_path, 'w'), indent=0)
    print(f'written: {out_path}  ({time.time()-t0:.0f}s)')
    for a, site, cur in indirect_rd[:20]:
        print(f'  reads flags after an indirect call: function {a:#x} call {site:#x} mask {cur:#x}')
    for a in sorted(flags_out)[:30]:
        print(f'  returns flags: {a:#x}')
    for a, v in sorted(live_in.items())[:0]: pass
    print('live at entry:', ' '.join(f'{a:#x}:{v:#x}' for a, v in sorted(live_in.items()) if v)[:2000])
